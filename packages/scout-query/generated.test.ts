// Parity by generation: a seeded generator makes random queries and labels
// from an alphabet built to stress the tokenizer (letters, digits, ':', '/',
// '\', straight and curly quotes and apostrophes, every WS code point, known
// field names). `fixtures/generated-cases.json` holds this implementation's
// results; the Rust port (`crates/scout-query/tests/fixtures.rs`) must
// reproduce every one exactly.
//
// Regenerate after a deliberate grammar change:
//   SCOUT_WRITE_FIXTURES=1 npx vitest run packages/scout-query/generated.test.ts
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, test } from "vitest";
import { parseSearch, quoteValue } from "./src/query";
import { WS } from "./src/scan";

const SEED = 20261011;
const QUERIES = 600;
const LABELS = 400;

/** mulberry32: a small deterministic PRNG. */
function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const LETTERS = ["a", "b", "Z", "é", "e", "́", "ž", "1", "9", "_"];
const PUNCT = [":", ":", "/", "/", "\\", "\\", '"', '"', "“", "”", "„", "‟",
  "'", "’", "‘", "-", "-", "*", "|", "(", ")", ".", ","];
const WORDS = ["theme", "au", "tag", "event", "tw", "i", "in", "month", "source", "zo", "y",
  "THEME", "Au", "zotero", "or", "OR", "and", "AND", "the", "of", "proof", "2026-09", "E21"];

function pick<T>(r: () => number, xs: readonly T[]): T {
  return xs[Math.floor(r() * xs.length)];
}

const FIELDS = ["theme", "entity", "event", "au", "ti", "tag", "tw", "in", "month", "source",
  "y", "i", "zo", "co", "ai", "THEME", "Au", "bo", "after"];

function atom(r: () => number): string {
  const x = r();
  if (x < 0.12) return " ";
  if (x < 0.2) return pick(r, WS);
  // Construct-shaped atoms, so fields, regexes and phrases do occur.
  if (x < 0.31) return `${pick(r, WS)}${pick(r, FIELDS)}:`;
  if (x < 0.35) return `${pick(r, WS)}/`;
  if (x < 0.39) return `/${pick(r, ["", "i", "g", "I"])}${pick(r, WS)}`;
  if (x < 0.43) return `${pick(r, WS)}${pick(r, ["", "-"])}${pick(r, ['"', "\u201C", "\u201E"])}`;
  if (x < 0.48) return `${pick(r, WS)}${pick(r, FIELDS)}:${pick(r, ['"', "\u201C", "\u201E"])}`;
  if (x < 0.65) return pick(r, PUNCT);
  if (x < 0.82) return pick(r, WORDS);
  return pick(r, LETTERS);
}

/** A parse result without its default-valued keys (null, false, "", []). */
function sparse(p: object): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(p)) {
    if (v === null || v === false || v === "" || (Array.isArray(v) && v.length === 0)) continue;
    out[k] = v;
  }
  return out;
}

function generate(): { queries: Array<{ input: string; partial: boolean }>; labels: string[] } {
  const r = rng(SEED);
  const queries = [];
  for (let i = 0; i < QUERIES; i += 1) {
    const n = 1 + Math.floor(r() * 14);
    let input = "";
    for (let k = 0; k < n; k += 1) input += atom(r);
    queries.push({ input, partial: i % 5 === 0 });
  }
  const labels = [];
  for (let i = 0; i < LABELS; i += 1) {
    const n = 1 + Math.floor(r() * 8);
    let label = "";
    for (let k = 0; k < n; k += 1) label += atom(r);
    labels.push(label);
  }
  return { queries, labels };
}

interface Fixture {
  about: string;
  seed: number;
  parse: Array<{ input: string; partial: boolean; expected: unknown }>;
  quote: Array<{ label: string; quoted: string }>;
}

const path = fileURLToPath(new URL("./fixtures/generated-cases.json", import.meta.url));
const generated = generate();

if (process.env.SCOUT_WRITE_FIXTURES) {
  const out: Fixture = {
    about:
      "Generated by packages/scout-query/generated.test.ts (seeded). TS results with default-valued keys (null, false, \"\", []) left out; the Rust port must match exactly. Do not edit by hand.",
    seed: SEED,
    parse: generated.queries.map((q) => ({ ...q, expected: sparse(parseSearch(q.input, q.partial)) })),
    quote: generated.labels.map((label) => ({ label, quoted: quoteValue(label) })),
  };
  // One case per line.
  const lines = (xs: unknown[]) => xs.map((x) => `  ${JSON.stringify(x)}`).join(",\n");
  writeFileSync(
    path,
    `{\n "about": ${JSON.stringify(out.about)},\n "seed": ${out.seed},\n "parse": [\n${lines(out.parse)}\n ],\n "quote": [\n${lines(out.quote)}\n ]\n}\n`,
  );
}

const fixture: Fixture = JSON.parse(readFileSync(path, "utf8"));

describe("generated grammar parity cases", () => {
  test("the fixture is this generator's output", () => {
    expect(fixture.seed).toBe(SEED);
    expect(fixture.parse.length).toBeGreaterThanOrEqual(500);
    expect(fixture.quote.length).toBeGreaterThanOrEqual(300);
    expect(fixture.parse.map((c) => ({ input: c.input, partial: c.partial }))).toEqual(generated.queries);
    expect(fixture.quote.map((c) => c.label)).toEqual(generated.labels);
  });

  test("the alphabet covers every WS code point, quote variant and construct", () => {
    const all = generated.queries.map((q) => q.input).join("");
    for (const c of [...WS, '"', "“", "”", "„", "‟", "'", "’", ":", "/", "\\"]) {
      expect(all.includes(c), `U+${c.charCodeAt(0).toString(16)}`).toBe(true);
    }
    const parsed = fixture.parse.map((c) => c.expected as Record<string, unknown>);
    const withKey = (k: string) => parsed.filter((p) => k in p).length;
    expect(withKey("theme")).toBeGreaterThan(20);
    expect(withKey("regexes")).toBeGreaterThan(20);
    expect(withKey("negatives")).toBeGreaterThan(20);
    expect(withKey("author")).toBeGreaterThan(10);
    // Quoted field values with a space inside, and quoted labels.
    const quotedValues = parsed.filter((p) =>
      ["theme", "entity", "event", "author", "title", "tag"].some(
        (k) => typeof p[k] === "string" && WS.some((w) => (p[k] as string).includes(w)),
      ),
    );
    expect(quotedValues.length).toBeGreaterThan(10);
    expect(fixture.quote.filter((c) => c.quoted.startsWith('"')).length).toBeGreaterThan(100);
    expect(fixture.quote.filter((c) => !c.quoted.startsWith('"')).length).toBeGreaterThan(30);
  });

  test("parseSearch reproduces every generated case", () => {
    for (const c of fixture.parse) {
      expect(sparse(parseSearch(c.input, c.partial)), JSON.stringify(c.input)).toEqual(c.expected);
    }
  });

  test("quoteValue reproduces every label and the label reads back unchanged", () => {
    for (const c of fixture.quote) {
      expect(quoteValue(c.label), JSON.stringify(c.label)).toBe(c.quoted);
      for (const q of [`theme:${c.quoted}`, `x theme:${c.quoted} y`, `theme:${c.quoted} /re/`]) {
        expect(parseSearch(q).theme, JSON.stringify(q)).toBe(c.label);
      }
    }
  });
});
